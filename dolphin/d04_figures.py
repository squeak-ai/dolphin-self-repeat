"""Article figures for the dolphin self-repeat paper. PNG 300 dpi + PDF into figures/.

Code name → article figure mapping (after renumbering):
  fig5 → Fig 1  example bouts: contour overlays + one real-time sequence         (features.pkl contours)
  fig1 → Fig 2  exact vs transposed triangles, both nulls, per-session replication (d04_triangles.json)
  fig3 → Fig 3  pitch invariance: P(shape match | |df|) at long lag vs short lag   (d04_renull.json)
  fig2 → Fig 4  gap-resolved exact-pair excess, within-minute null                 (d04_renull.json)
  fig4 → Fig 5  threshold sweep of the excess pair count                           (d04_threshold.json)
Cross-species figures (Fig 6–8) are generated by marmoset/m06_crossspecies.py.
Style: shared figstyle.py. Species colour is fixed across all article figures: dolphin = orange (observed/exact),
darker burnt orange for the secondary dolphin series (transposed), nulls = neutral greys. All figures 10 in wide,
12 pt labels / 10 pt ticks, PNG 300 dpi + vector PDF.
"""
