b.set_xscale('log'); b.set_yscale('log'); b.set_xlim(lim); b.set_ylim(lim)
for setter, lab in [(b.set_xticks, b.set_xticklabels), (b.set_yticks, b.set_yticklabels)]:
    setter([0.25, 1, 10, 100, 1000]); lab(['0', '1', '10', '100', '1000'])
b.xaxis.set_minor_locator(matplotlib.ticker.NullLocator()); b.yaxis.set_minor_locator(matplotlib.ticker.NullLocator())
b.legend(loc='upper left', labelspacing=0.8, handletextpad=0.3, borderaxespad=0.1, facecolor=SURF, framealpha=0.9, frameon=True, edgecolor='none'); panel_label(b, 'b')
headline(f, 'Mutually-exact whistle triples are 2.5× chance; transposed triples are at chance', y=1.03)
out(f, 'article_fig1')

