# ================= Figure 5: example bouts =================
df, F = load(); C = F['C']
def sess_tag(w):                  # session number + recording date, read from the data (not hand-typed)
    d = str(int(df.date.values[w])); return f"session {int(df.session.values[w])} ({d[:4]}-{d[4:6]}-{d[6:]})"


bouts = [('Rise', [264, 271, 273]), ('U', [2349, 2351, 2353]), ('Arch', [4472, 4481, 4487, 4492, 4497])]
bouts = [(f'{name} — {sess_tag(ix[0])}' + (f', {len(ix)} renditions' if len(ix) > 3 else ''), ix) for name, ix in bouts]
seq = [3987, 3988, 3989, 3990, 3991, 3992, 3993, 3994, 3995]
f = plt.figure(figsize=(FULL_W, 7.8)); gs = f.add_gridspec(2, 3, height_ratios=[1.35, 1], hspace=0.5, wspace=0.3)
for k, (title, ix) in enumerate(bouts):
    ax = f.add_subplot(gs[0, k]); style(ax, xlabel='time from whistle onset (s)', ylabel='frequency (kHz)' if k == 0 else None)
    t0s = df.abs_t0.values[ix]; cols = BLUES[:len(ix)] if len(ix) <= 3 else BLUES
    if len(ix) == 3: cols = [BLUES[0], BLUES[2], BLUES[4]]
    for i, (w, c) in enumerate(zip(ix, cols)):
        a_ = C[w]; ax.plot(a_[:, 0] - a_[0, 0], a_[:, 1] / 1000, color=c, lw=2, alpha=0.95, label=f'+{t0s[i] - t0s[0]:.1f} s' if i else '0 s')
    ax.set_title(title, loc='left', fontsize=FS_ANNO); ax.legend(title='onset', loc='best', handlelength=1.2, fontsize=FS_SMALL)
    ax.set_ylim(min(C[w][:, 1].min() for w in ix) / 1000 - 1, max(C[w][:, 1].max() for w in ix) / 1000 + 1)
    panel_label(ax, 'abc'[k])
# (d) the real-time sequence
ax = f.add_subplot(gs[1, :]); style(ax, xlabel=f'time (s) — {sess_tag(seq[0])}, one-minute file', ylabel='frequency (kHz)')
t_ref = df.abs_t0.values[seq[0]]
thr = tri['thr_abs']; Da = np.load(os.path.join(OUT, 'dtw_abs.npy'))
for w in seq:
    a_ = C[w]; is_arch = df.cls.astype(str).values[w] == 'arch'
    ax.plot(df.file_start.values[w] + a_[:, 0] - t_ref, a_[:, 1] / 1000, color=DOLPHIN if is_arch else G3, lw=2)
ax.text(df.abs_t0.values[3992] - t_ref + 0.35, 14.3, 'U — not exact to any arch', fontsize=FS_SMALL, color=G3, va='bottom', ha='center')
n_ex = int((Da[np.ix_(seq, seq)] <= thr).sum() - len(seq)) // 2
ax.set_title(f'Eight arch renditions in 31 s, {n_ex} of 28 arch pairs exact (DTW-abs ≤ p5); one U interleaved', loc='left', fontsize=FS_ANNO)
ax.set_ylim(4, 16); ax.set_xlim(-1, 32); panel_label(ax, 'd')
headline(f, 'Example bouts: the same contour at the same absolute frequency, seconds apart', y=0.965)
out(f, 'article_fig5')
